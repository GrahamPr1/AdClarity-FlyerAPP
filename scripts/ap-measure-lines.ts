/**
 * Pins lib/ap/templates/max-lines.ts: renders each layout with the text the
 * kit was supplied with (tests/fixtures-ap-supplied-slots.json, English and
 * Spanish) in the real renderer, and records each slot's line count. The max
 * of the two languages is that slot's line limit for every org.
 *
 * Usage: npx tsx scripts/ap-measure-lines.ts  (prints the file; --write writes it)
 */
import fs from "node:fs"
import { renderFlyer } from "../lib/ap/templates/render"
import { logoHtml } from "../lib/ap/templates/logo"
import { LAYOUTS, type Layout } from "../lib/ap/templates/slots"

const supplied = JSON.parse(fs.readFileSync("tests/fixtures-ap-supplied-slots.json", "utf8")) as Record<Layout, Record<string, { EN: string; ES: string }>>
const spacingFor = (layout: Layout, lang: "en" | "es") => (layout === "P1" ? (lang === "es" ? "tight" : "supplied") : "approved")

async function main() {
  const out: Record<string, Record<string, number>> = {}
  for (const layout of LAYOUTS) {
    out[layout] = {}
    for (const lang of ["en", "es"] as const) {
      const slots = Object.fromEntries(Object.entries(supplied[layout]).map(([k, v]) => [k, lang === "en" ? v.EN : v.ES]))
      const r = await renderFlyer(
        {
          layout, lang, size: "letter", showPrice: true, title: "measure", screenLabel: "measure",
          logoHtml: logoHtml(null, "Sample Benefits Co."), slots,
          agent: { name: "Pat Sample", phone: "(502) 555-0100", link: { href: "https://example.org/ap/q/Abc2345", lines: ["example.org/ap/q/Abc2345"] }, qr: "https://example.org/ap/q/Abc2345" },
          spacing: spacingFor(layout, lang), expectHash: null, proof: false, calibrate: true,
        },
        null,
      ).catch((e) => { console.error(layout, lang, e.message); throw e })
      for (const s of r.measure.slots) if (s.visible) out[layout][s.key] = Math.max(out[layout][s.key] ?? 0, s.lines)
      console.error(`${layout} ${lang}: minGap ${r.measure.minGap.toFixed(1)}px, mainOverflow ${r.measure.mainOverflow}`)
    }
  }
  const body = `import type { Layout } from "./slots"

// GENERATED by scripts/ap-measure-lines.ts: each slot's line count when the
// kit's supplied text (English and Spanish, the larger) is rendered in the
// real renderer. A slot that renders on more lines than this is refused.
export const MAX_LINES: Record<Layout, Record<string, number>> = ${JSON.stringify(out, null, 2)}
`
  if (process.argv.includes("--write")) fs.writeFileSync("lib/ap/templates/max-lines.ts", body)
  console.log(body)
  process.exit(0)
}
main()

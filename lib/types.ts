// ---------------------------------------------------------------------------
// OneFlyer shared data contracts
//
// These interfaces define the shapes exchanged between the marketing site,
// the client dashboard, and the EXTERNAL Claude-based agent pipeline (built
// outside of v0). Keep them stable so the pipeline can match up cleanly.
// ---------------------------------------------------------------------------

// The three real tiers — used BOTH for the marketing pricing page a visitor
// picks from AND as the real enforcement flag on a client's persisted
// record (see ClientRecord below). Picking a tier on the marketing page
// (via the onboarding ?plan= query string) is only ever a REQUEST — it does
// NOT by itself grant that plan. A client's real enforcement plan only ever
// changes via the admin route (POST /api/admin/set-plan), never inferred
// from an IntakeSubmission's planId — there's no real Stripe billing wired
// up yet, so trusting a client-selected value for enforcement would let
// anyone grant themselves Basic/Pro just by editing the URL.
export type PlanId = "trial" | "basic" | "pro"

// Real per-plan flyer caps — the single source of truth for both real
// enforcement (lib/store.ts, app/api/intake/route.ts) and marketing copy
// (lib/plans.ts), so the two can't drift out of sync the way the old
// marketing numbers did before this existed.
//
// NOTE: all three are LIFETIME caps for now, not periodic ones. Basic/Pro
// are priced as monthly subscriptions, but with no real Stripe billing
// wired up yet there's no real subscription period to reset against —
// inventing a self-maintained reset timer with nothing backing it would
// just be a different kind of dishonest. Swap this to a real
// current_period_start/end -based reset once Stripe billing exists.
export const PLAN_LIMITS: Record<PlanId, number> = {
  trial: 3,
  basic: 15,
  pro: 25,
}

export interface Plan {
  id: PlanId
  name: string
  /** Short punchy positioning line under the name */
  tagline: string
  /** Small badge shown on the card, e.g. "Most Popular" */
  badge?: string
  /** Recurring monthly fee in whole dollars. 0 for the free trial tier. */
  monthlyFee: number
  description: string
  features: string[]
  /** A short callout reinforcing what this tier is for */
  note: string
  /** A short outcome-focused line reinforcing the result they get */
  outcome: string
  mostPopular?: boolean
  /** Placeholder Stripe price ID — wire this to a real price once a Stripe account exists. Unused for the free trial tier. */
  stripeMonthlyPriceId?: string
  ctaLabel: string
  /**
   * If set, the CTA renders as a plain link to this href instead of
   * triggering onSubscribe — for a tier with no real self-serve checkout
   * yet (e.g. a mailto: contact link). A button whose label promises an
   * upgrade but silently does nothing is worse than an honest "contact us."
   * Unused for all three current tiers — every button routes to onboarding.
   */
  ctaHref?: string
}

/** Shared reassurance line shown beneath all plans */
export const PLAN_GUARANTEE = "Cancel anytime · You own every flyer you generate"

/** Explains how the three tiers relate, shown beneath the pricing grid */
export const PLAN_EXPLAINER =
  "Every flyer is generated by our AI design engine and automatically brand-matched to your business — colors, fonts, and layout, no design skills required. Start with a free trial, then choose Basic or Pro as your business grows."

// ---- Intake / onboarding -------------------------------------------------

export type BrandStyle = "modern" | "classic" | "playful" | "minimal"

export interface ServiceItem {
  id: string
  name: string
}

export interface IntakeSubmission {
  planId: PlanId | null
  businessName: string
  industry: string
  yearsInBusiness: string
  services: ServiceItem[]
  logoFileName?: string
  brandColors?: string
  preferredStyle: BrandStyle
  voiceTone: string
  targetAudience: string
  contact: {
    email: string
    phone: string
    address: string
    website: string
    socialHandles: string
  }
  existingMaterialsFileName?: string
  flyerNotes: string
  websitePreferences: string
  submittedAt?: string
}

// ---- Client records (usage limits) ---------------------------------------

// Persisted per-email record used for real enforcement of each plan's
// flyer limit (see PLAN_LIMITS). plan here is authoritative and only
// changes via the admin route — never inferred from an IntakeSubmission's
// planId (see the note on PlanId above).
export interface ClientRecord {
  email: string
  plan: PlanId
  /** Lifetime count — never resets (see the note on PLAN_LIMITS above). Incremented before the flyers it counts are generated. */
  flyersCreated: number
}

// ---- Deliverables / dashboard --------------------------------------------

export type FlyerStatus = "Pending" | "In Progress" | "Ready" | "Failed"
export type IntakeStatus = "Submitted" | "Not started"
export type BillingStatus = "Active" | "Past due" | "Trialing"

export interface FlyerDeliverable {
  id: string
  title: string
  status: FlyerStatus
  thumbnailUrl?: string
  downloadUrl?: string
  /** Set when status is "Failed" — shown to the client, with a retry option. */
  error?: string
}

export interface Deliverables {
  planId: PlanId
  planName: string
  billingStatus: BillingStatus
  intakeStatus: IntakeStatus
  flyers: FlyerDeliverable[]
  /** The latest submitter's real usage, for the dashboard's usage indicator. Null email = no intake yet. */
  email: string | null
  flyersCreated: number
  /** Always a real cap now — no plan is unlimited (see PLAN_LIMITS). */
  flyersLimit: number
}

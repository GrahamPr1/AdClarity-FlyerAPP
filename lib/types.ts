// A client's saved default info source for form-fill — the same shape
// form-fill already accepts per-request (a file and/or a link), just
// persisted so it doesn't need to be re-uploaded every time. Pro-only, same
// as form-fill itself.
export interface BusinessProfileRecord {
  savedAt: string
  link: string | null
  file: { blobUrl: string; mediaType: string; fileName: string } | null
}

// ---- Saved brand profile (Quick Prompt) -------------------------------------
//
// Distinct from BusinessProfileRecord above (form-fill's saved info source —
// a raw file/link, not brand data) despite the similar name in this app's
// own product spec — this is a real gap that had to be filled: the guided
// flow already collects colors/logo/voice/contact every submission, but
// none of it was ever persisted per-client before Quick Prompt needed to
// reuse it. Stores the REAL Brand Agent output (see BrandProfile in
// lib/agent-pipeline/schemas/brand.ts) rather than a separate parallel
// schema, so "the same one used by Guided Setup" is literally true, not
// just similar. Refreshed automatically after every successful guided
// generation; for Quick Prompt, only ever written once, on explicit opt-in
// (see POST /api/brand-profile/save) — an AI-inferred brand from a single
// vague prompt is a much weaker signal than a client who filled out the
// real form, so it doesn't get to overwrite silently.
//
// contact is carried separately from brandProfile: BrandProfile (the Brand
// Agent's own output) has no phone/address/website/social fields at all —
// that lives on the ORIGINAL intake instead — so a Quick Prompt submission
// reusing a saved brand still needs somewhere to get real contact info
// from without asking for it again every time.
export interface SavedBrandProfile {
  savedAt: string
  brandProfile: BrandProfile
  contact: NormalizedIntake["contact"]
}

// ---- AI generation cost log -------------------------------------------------
//
// One row per real Claude API call in the Intake/Brand/Flyer pipeline — NOT
// one row per flyer. A single Flyer Agent call can produce several flyers
// in one batch, so flyerId is null whenever an entry doesn't map to exactly
// one flyer (a batch of more than one, or the Intake/Brand stages, which
// each run once per submission before any flyer id exists yet). email is
// this app's real per-account identity (see ClientRecord) — there's no
// separate "business" entity distinct from the account itself, so there's
// no businessId field here.

// "quick_prompt" is the lightweight parser that replaces the Intake Agent
// on the Quick Prompt path (see lib/agent-pipeline/agents/quickPromptAgent.ts)
// — a distinct stage so admin cost views can see quick-prompt usage
// separately from guided usage, even though the SAME "brand"/"flyer" stages
// run downstream either way (see PIPELINE_TIMEOUT_MS's caller in
// lib/agent-pipeline/pipeline.ts — those two agents are never changed).
// "scrape" is the extraction call that turns crawled website text into the
// same shape the Intake Agent produces (see lib/agent-pipeline/agents/scrapeAgent.ts)
// on the website-auto-fill onboarding path — the actual crawling itself is
// pure code with no Claude call, so nothing logs for that part.
export type GenerationAgentType = "intake" | "brand" | "flyer" | "quick_prompt" | "scrape"

export interface GenerationLogEntry {
  id: string
  email: string
  flyerId: string | null
  agentType: GenerationAgentType
  model: string
  inputTokens: number
  outputTokens: number
  estimatedCostUsd: number
  createdAt: string
}

// ---- Admin dashboard (/admin) ------------------------------------------------
//
// There's no real "canceled" status yet — no Stripe subscription exists to
// cancel (see the admin spec's own phase 4, gated on Stripe being
// connected) — so status is only ever "trial" or "active" for now, never
// fabricated as "canceled".

export type AdminUserStatus = "trial" | "active"

export interface AdminUserRow {
  email: string
  /** From this client's most recent onboarding submission — see ClientRecord.businessName. Null if they've never onboarded. */
  businessName: string | null
  plan: PlanId
  businessCategory: BusinessCategory
  /** ISO signup timestamp — see ClientRecord.createdAt. Null in the (should be rare) case a real user record predates this field entirely. */
  createdAt: string | null
  flyersCreated: number
  flyersLimit: number
  status: AdminUserStatus
  isAdmin: boolean
}

export interface AdminUsersOverview {
  totalUsers: number
  newSignupsThisWeek: number
  newSignupsThisMonth: number
  /** Daily signup counts for the last 30 days, oldest first — the users-page trend chart. */
  signupTrend: { date: string; count: number }[]
  byPlan: Record<PlanId, number>
  byCategory: Record<BusinessCategory, number>
  users: AdminUserRow[]
}

export interface AdminUserDetail extends AdminUserRow {
  generationLog: GenerationLogEntry[]
  totalEstimatedCostUsd: number
}

// ---- Admin cost tracking (/admin/costs) --------------------------------------
//
// "This month" here means the same rolling 30-day window PLAN_LIMITS itself
// resets on (see RESET_PERIOD_MS in lib/store.ts) — this app has no fixed
// calendar-month billing period, so treating cost windows as calendar
// months would be a fake precision the rest of the app doesn't have either.

export interface AdminCostUserRow {
  email: string
  businessName: string | null
  plan: PlanId
  monthlyCostUsd: number
  /** This user's plan tier's average per-user cost this month — the denominator behind isOutlier, computed across every user on the plan, not just the ones shown here. */
  planAverageCostUsd: number
  /** True when monthlyCostUsd > 3x planAverageCostUsd. */
  isOutlier: boolean
}

export interface AdminCostsOverview {
  totalCostTodayUsd: number
  totalCostThisWeekUsd: number
  totalCostThisMonthUsd: number
  /** Daily cost buckets, last 30 days, oldest first — the trend chart. */
  costTrend: { date: string; cost: number }[]
  /** Average cost of one Flyer Agent API call over the last 30 days — not exactly "per flyer produced" when one call covers a multi-flyer batch (see GenerationLogEntry.flyerId), but that's the overwhelmingly common case. */
  averageCostPerFlyerGenerationUsd: number
  /** Total cost by pipeline stage, last 30 days. */
  costByAgentType: Record<GenerationAgentType, number>
  /** Every plan tier's average per-user cost this month. */
  planAverageCostUsd: Record<PlanId, number>
  /** Top 20 highest-cost users this month, sorted descending — the outlier/abuse-detection view. */
  topCostUsers: AdminCostUserRow[]
}


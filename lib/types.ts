// OneFlyer shared data contracts
//
// These interfaces define the shapes exchanged between the marketing site,
// the client dashboard, and the EXTERNAL Claude-based agent pipeline (built
// outside of v0). Keep them stable so the pipeline can match up cleanly.
// ---------------------------------------------------------------------------

import type { BrandProfile } from "./agent-pipeline/schemas/brand"
import type { NormalizedIntake } from "./agent-pipeline/schemas/intake"

// The three real tiers — used BOTH for the marketing pricing page a visitor
// picks from AND as the real enforcement flag on a client's persisted
// record (see ClientRecord below). Picking a tier on the marketing page
// (via the onboarding ?plan= query string) is only ever a REQUEST — it does
// NOT by itself grant that plan. A client's real enforcement plan only ever
// changes via the admin route (POST /api/admin/set-plan), never inferred
// from an IntakeSubmission's planId — there's no real Stripe billing wired
// up yet, so trusting a client-selected value for enforcement would let
// anyone grant themselves Basic/Pro just by editing the URL.
export type PlanId = "trial" | "basic" | "pro"

// Real per-plan flyer caps — the single source of truth for both real
// enforcement (lib/store.ts, app/api/intake/route.ts) and marketing copy
// (lib/plans.ts), so the two can't drift out of sync the way the old
// marketing numbers did before this existed.
//
// These reset every 30 days from each client's own tracked period start
// (see ClientRecord.periodStart) — a real, enforced rolling window, not
// just a display label. Anchored to our own clock rather than a Stripe
// billing period since no real Stripe subscription exists yet; once it
// does, periodStart can be re-anchored to Stripe's current_period_start.
export const PLAN_LIMITS: Record<PlanId, number> = {
  trial: 3,
  basic: 25,
  pro: 50,
}

// Single source of truth for the annual-billing discount shown on the
// pricing page — the displayed "Save X%" badge and every plan's
// annualMonthlyFee (see lib/plans.ts) both read this, so changing the
// discount later never means hunting down multiple hand-typed numbers.
export const ANNUAL_DISCOUNT_PERCENT = 20

export interface Plan {
  id: PlanId
  name: string
  /** Short punchy positioning line under the name */
  tagline: string
  /** Small badge shown on the card, e.g. "Most Popular" */
  badge?: string
  /** Recurring monthly fee in whole dollars. 0 for the free trial tier. */
  monthlyFee: number
  /** Monthly-equivalent price when billed annually — always monthlyFee * (1 - ANNUAL_DISCOUNT_PERCENT / 100), computed once in lib/plans.ts rather than hand-typed per plan, so it can't drift if monthlyFee or the discount changes. 0 for the free trial tier. */
  annualMonthlyFee: number
  description: string
  features: string[]
  /** A short callout reinforcing what this tier is for */
  note: string
  /** A short outcome-focused line reinforcing the result they get */
  outcome: string
  mostPopular?: boolean
  /** Placeholder Stripe price ID — wire this to a real price once a Stripe account exists. Unused for the free trial tier. */
  stripeMonthlyPriceId?: string
  /** Placeholder Stripe price ID for the annual billing interval — same treatment as stripeMonthlyPriceId, wire once Stripe exists. Unused for the free trial tier. */
  stripeAnnualPriceId?: string
  ctaLabel: string
  /**
   * If set, the CTA renders as a plain link to this href instead of
   * triggering onSubscribe — for a tier with no real self-serve checkout
   * yet (e.g. a mailto: contact link). A button whose label promises an
   * upgrade but silently does nothing is worse than an honest "contact us."
   * Unused for all three current tiers — every button routes to onboarding.
   */
  ctaHref?: string
}

/** Shared reassurance line shown beneath all plans */

// ---- Campaign defaults (optional profile) ----------------------------------
//
// The reusable half of an intake submission: brand identity and contact
// details that are the SAME for every campaign this business ever runs.
//
// These used to sit inside the onboarding form as steps 4 and 6, which meant
// a brand-new user had to page through ~15 optional inputs before they could
// see a single flyer — even though only five fields are actually required to
// generate one. They're now collected here instead, after the first campaign
// exists and the product has proven itself, and merged into every subsequent
// submission as defaults (see OnboardingForm's initial state).
//
// Deliberately NOT the same thing as either existing "profile" record:
//   - BusinessProfileRecord is form-fill's saved info SOURCE (a file/link).
//   - SavedBrandProfile is the Brand Agent's own OUTPUT, inferred by AI.
// This one is the client's own raw answers, which is what should win when
// re-filling a form they'll see and edit.
export interface CampaignDefaults {
  savedAt: string
  yearsInBusiness: string
  brandColors: string
  preferredStyle: BrandStyle
  voiceTone: string
  contactName: string
  website: string
  address: string
  socialHandles: string
}

// ---- Client records (usage limits) ---------------------------------------

// Persisted per-email record used for real enforcement of each plan's
// flyer limit (see PLAN_LIMITS). plan here is authoritative and only
// changes via the admin route — never inferred from an IntakeSubmission's
// planId (see the note on PlanId above).
export interface ClientRecord {
  email: string
  plan: PlanId
  /** Count within the CURRENT 30-day period — resets to 0 when periodStart rolls over (see PLAN_LIMITS). Incremented before the flyers it counts are generated. */
  flyersCreated: number
  /** Epoch ms when the current 30-day usage period started. */
  periodStart: number
  /** Set at signup (see IntakeSubmission.businessCategory) or, for accounts that predate this field, via the dashboard's one-time banner (POST /api/business-category). Always a real value — defaults to "Other" when nothing has been explicitly set yet (see getClient in lib/store.ts), never null/undefined, so downstream features can rely on it being present. */
  businessCategory: BusinessCategory
  /** Pure derivation of businessCategory === "Real Estate / Wholesaling" — recomputed wherever a ClientRecord is assembled (lib/store.ts) rather than stored separately, so it can never drift out of sync with businessCategory. */
  isRealEstate: boolean
  /** Grants access to /admin/* (see app/admin/layout.tsx) on top of this client's own normal dashboard — distinct from ADMIN_SUB (the single site-owner password login, which always has /admin access too and is untouched by this flag). Only ever set via POST /api/admin/set-admin, itself gated to the ADMIN_SUB session — an isAdmin account can't grant admin to anyone else. Defaults to false. */
  isAdmin: boolean
  /** The business name from this client's most recent onboarding submission — null if they've never onboarded. Set directly by /api/intake, same treatment as businessCategory: never touched by the AI pipeline, just carried through from the raw submission. This is the closest thing this app has to a client-facing "name" (there's no separate person-name field anywhere — onboarding only ever asks for the business). */
  businessName: string | null
  /** Real signup timestamp (ISO) — the first time this email ever got a real password credential (signup, or claiming a pre-password-era account via the reset-password flow). Deliberately NOT periodStart, which rolls forward every 30 days as the usage window resets and so can't answer "when did this account first exist". Null for an account that was created via getOrCreateClient (e.g. by submitting onboarding) but has never actually signed up with a password. */
  createdAt: string | null
  /**
   * Total campaigns ever created, across all usage periods — never resets.
   * flyersCreated above CANNOT answer this: it's the current 30-day window's
   * count and rolls back to 0 (see rollPeriodIfExpired), so the single most
   * important retention question — "did they come back and make another?" —
   * is unanswerable without this. 0 for accounts predating this counter.
   */
  lifetimeFlyersCreated: number
  /** ISO timestamp of the most recent campaign creation — the other half of retention (recency, alongside lifetime frequency). Null if they've never created one, or predate this counter. */
  lastCampaignAt: string | null
  /**
   * When the client paused their account, or null if active.
   *
   * Pausing stops NEW campaign creation and (once Stripe is connected) stops
   * billing. It deliberately deletes nothing — the brand profile, every flyer
   * already generated, and all QR tracking history stay exactly as they were,
   * so resuming is not the same as starting over. It exists so that "I need a
   * break" has an answer that isn't "cancel and lose everything".
   */
  pausedAt: string | null
}

